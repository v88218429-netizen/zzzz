def _program_score(group: dict[str, Any]) -> int:
    p = _PRIORITY_SCORE.get(str(group.get("priority") or "low"), 1)
    affected = min(20, int(group.get("affected_count") or 0))
    review = min(10, int(group.get("needs_review_count") or 0))
    impact = 5 if group.get("frozen_capital_rub") else 0
    return min(100, p * 18 + affected + review + impact)


def build_research_agenda(
    groups: list[dict[str, Any]],
    portfolio_quality: dict[str, Any] | None = None,
    dataset_quality: dict[str, Any] | None = None,
) -> dict[str, Any]:
    programs: list[dict[str, Any]] = []
    for group in groups or []:
        gid = str(group.get("group_id") or "")
        play = _PLAYBOOKS.get(gid)
        if not play:
            continue
        programs.append({
            "program_id": f"research:{gid}",
            "title": group.get("title"),
            "objective": group.get("question"),
            "priority_score": _program_score(group),
            "trigger": {
                "decisions": group.get("decision_count"),
                "affected": group.get("affected_count"),
                "needs_review": group.get("needs_review_count"),
                "frozen_capital_rub": group.get("frozen_capital_rub"),
            },
            "hypotheses": play["hypotheses"],
            "tests": play["tests"],
            "success_condition": play["success"],
            "loop": "наблюдения → конкурирующие гипотезы → тест/эксперимент → измерение → обновление модели → следующий тест",
            "mode": "research",
        })

    pq = portfolio_quality or {}
    if int(pq.get("products_total") or 0) >= 30:
        programs.append({
            "program_id": "research:cross_sku_discovery",
            "title": "Поиск новых закономерностей между SKU",
            "objective": "Найти повторяемые связи, которых нет в текущих правилах: цена↔спрос, реклама↔органика, запас↔позиция, маржа↔масштабирование и перенос спроса между SKU.",
            "priority_score": 55,
            "trigger": {"products": pq.get("products_total")},
            "hypotheses": [
                "Одинаковые изменения дают разный эффект в разных категориях и режимах спроса.",
                "Существуют группы SKU, у которых одна управляющая переменная систематически предсказывает следующий сдвиг другой.",
                "Часть текущих правил можно заменить обученными на собственной истории порогами.",
            ],
            "tests": [
                "Искать связи сначала внутри сопоставимых категорий и временных окон, затем проверять их на holdout-периоде.",
                "Контролировать множественные проверки и не превращать корреляцию в причинный вывод.",
                "После обнаружения устойчивой связи формировать минимальный безопасный эксперимент и проверять повторяемость.",
            ],
            "success_condition": "Новая закономерность считается знанием только после повторной проверки на данных, которые не использовались для её открытия.",
            "loop": "pattern mining → гипотеза → holdout/backtest → эксперимент → причинная проверка → новое правило",
            "mode": "discovery",
        })

    dq = dataset_quality or {}
    if int(dq.get("datasets_degraded") or 0) > 0:
        programs.append({
            "program_id": "research:information_gain",
            "title": "Ценность следующего измерения",
            "objective": "Выбирать, какой недостающий источник или эксперимент даст максимальное снижение неопределённости для денежных решений.",
            "priority_score": 70,
            "trigger": {"datasets_degraded": dq.get("datasets_degraded")},
            "hypotheses": [
                "Не все пробелы данных одинаково важны: некоторые не меняют решений, другие блокируют десятки SKU.",
            ],
            "tests": [
                "Для каждого отсутствующего источника считать, сколько решений и рублей риска зависят от него.",
                "Сначала восстанавливать данные с максимальной ожидаемой ценностью информации.",
            ],
            "success_condition": "Очередь сбора данных оптимизируется по влиянию на решения, а не по удобству исправления.",
            "loop": "неопределённость → ожидаемая ценность информации → сбор данных → пересчёт решений",
            "mode": "active_learning",
        })

    programs.sort(key=lambda x: -int(x.get("priority_score") or 0))
    return {
        "programs": programs,
        "count": len(programs),
        "principle": "База данных — стартовая модель мира. Агент должен использовать её для генерации новых проверяемых гипотез и расширять знание только через проверку.",
    }
